import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MODULE_DIR = path.dirname(fileURLToPath(import.meta.url));
const EPSILON_REMAINING_FRACTION = 1e-12;
const LOG_CHART_FLOOR = 1e-6;

export const DEFAULT_LIGHT_EXTENT_CONFIG_PATH = path.join(
	MODULE_DIR,
	'../data/reference/light-extent-scenarios.json',
);

export function loadLightExtentConfig(configPath = DEFAULT_LIGHT_EXTENT_CONFIG_PATH) {
	return JSON.parse(fs.readFileSync(path.resolve(configPath), 'utf8'));
}

export function runLightExtentProbeSet(config, {
	selectedIds = [],
	configPath = DEFAULT_LIGHT_EXTENT_CONFIG_PATH,
} = {}) {
	const sets = readScenarioSets(config);
	const selectedSetIds = selectedIds.length ? selectedIds : sets.map((set) => set.id);
	const lightExtents = selectedSetIds.map((id) => {
		const set = sets.find((candidate) => candidate.id === id);

		if (!set) {
			throw new Error(`Unknown light extent set: ${id}`);
		}

		return runLightExtentProbe(materializeScenario(config.defaults ?? {}, set));
	});

	return {
		kind: 'flat-atmosphere-reference-light-extent',
		generatedAt: null,
		generatedAtPolicy: 'omitted-for-deterministic-output',
		configPath: normalizeOutputPath(configPath),
		lightExtentCount: lightExtents.length,
		thresholdSemantics: {
			lossFractionRange: '[0, 1)',
			opacityLossFraction: '0 means no source-path transmission has been lost. Values close to 1 mean the path is nearly opaque; use 0.999999 instead of exact 1 because Beer-Lambert transmittance approaches zero asymptotically.',
			usefulLightLossFraction: '0 means no effective irradiance has been lost relative to the source-path start. Values close to 1 mean almost no useful source light remains after transmittance and finite-source solid-angle falloff.',
		},
		lightExtents,
	};
}

