function runLightExtentProbe(scenario) {
	const parameters = validateScenario(scenario);
	const baseline = evaluateAtDistance(parameters, parameters.path.startDistanceKm, null);
	const samples = buildCoarseSamples(parameters, baseline.effectiveIrradiance);
	const thresholdCrossings = {
		opacity: findCrossing(
			parameters,
			baseline.effectiveIrradiance,
			samples,
			'opacity',
			parameters.derivedThresholds.transmittanceThreshold,
			(sample) => sample.transmittance <= parameters.derivedThresholds.transmittanceThreshold,
		),
		usefulLight: findCrossing(
			parameters,
			baseline.effectiveIrradiance,
			samples,
			'usefulLight',
			parameters.derivedThresholds.relativeEffectiveIrradianceThreshold,
			(sample) => sample.relativeEffectiveIrradiance <= parameters.derivedThresholds.relativeEffectiveIrradianceThreshold,
		),
	};
	const floorCrossings = {
		effectiveIrradiance: parameters.floors.effectiveIrradiance.map((floor) => {
			const {
				remainingThreshold,
				lossFraction,
				...crossing
			} = findCrossing(
				parameters,
				baseline.effectiveIrradiance,
				samples,
				floor.id,
				floor.value,
				(sample) => sample.effectiveIrradiance <= floor.value,
			);

			return {
				...crossing,
				floorValue: floor.value,
				floor,
			};
		}),
	};

	return {
		id: scenario.id,
		label: scenario.label,
		description: scenario.description,
		parameters: stripDerivedParameters(parameters),
		derivedThresholds: parameters.derivedThresholds,
		sourceAvailability: {
			directLightAvailable: parameters.sun.directLightAvailable,
		},
		baseline: {
			distanceFromSunKm: baseline.distanceFromSunKm,
			solidAngleSr: baseline.solidAngleSr,
			effectiveIrradiance: baseline.effectiveIrradiance,
		},
		thresholdCrossings,
		floorCrossings,
		functionalExtent: chooseFunctionalExtent(thresholdCrossings),
		sampleCount: samples.length,
		samples,
	};
}

function materializeScenario(defaults, set) {
	const scenarioOverrides = { ...set };
	delete scenarioOverrides.id;
	delete scenarioOverrides.label;
	delete scenarioOverrides.description;

	return {
		id: requireText(set.id, 'set.id'),
		label: set.label ?? set.id,
		description: set.description ?? 'No description provided.',
		...deepMerge(defaults, scenarioOverrides),
	};
}

function validateScenario(scenario) {
	const referenceWavelengthNm = positiveFiniteNumber(scenario.referenceWavelengthNm, `${scenario.id}.referenceWavelengthNm`);
	const sun = {
		brightnessScale: nonnegativeFiniteNumber(scenario.sun?.brightnessScale, `${scenario.id}.sun.brightnessScale`),
		elevationDeg: finiteNumber(scenario.sun?.elevationDeg, `${scenario.id}.sun.elevationDeg`),
		directLightAvailable: scenario.sun?.directLightAvailable !== false,
	};
	const source = {
		radiusKm: positiveFiniteNumber(scenario.source?.radiusKm, `${scenario.id}.source.radiusKm`),
	};
	const atmosphere = {
		densityModel: requireDensityModel(scenario.atmosphere?.densityModel, `${scenario.id}.atmosphere.densityModel`),
		extinction550PerKm: nonnegativeFiniteNumber(scenario.atmosphere?.extinction550PerKm, `${scenario.id}.atmosphere.extinction550PerKm`),
		wavelengthExponent: finiteNumber(scenario.atmosphere?.wavelengthExponent, `${scenario.id}.atmosphere.wavelengthExponent`),
		scaleHeightKm: positiveFiniteNumber(scenario.atmosphere?.scaleHeightKm, `${scenario.id}.atmosphere.scaleHeightKm`),
		atmosphereTopKm: nonnegativeFiniteNumber(scenario.atmosphere?.atmosphereTopKm, `${scenario.id}.atmosphere.atmosphereTopKm`),
	};
	const pathParameters = {
		startDistanceKm: positiveFiniteNumber(scenario.path?.startDistanceKm, `${scenario.id}.path.startDistanceKm`),
		maxDistanceKm: positiveFiniteNumber(scenario.path?.maxDistanceKm, `${scenario.id}.path.maxDistanceKm`),
		startAltitudeKm: finiteNumber(scenario.path?.startAltitudeKm, `${scenario.id}.path.startAltitudeKm`),
	};
	const sampling = {
		coarseSampleCount: positiveInteger(scenario.sampling?.coarseSampleCount, `${scenario.id}.sampling.coarseSampleCount`, 2),
		integrationStepKm: positiveFiniteNumber(scenario.sampling?.integrationStepKm, `${scenario.id}.sampling.integrationStepKm`),
		binaryIterations: nonnegativeInteger(scenario.sampling?.binaryIterations, `${scenario.id}.sampling.binaryIterations`),
	};
	const thresholds = {
		opacityLossFraction: thresholdLossFraction(scenario.thresholds?.opacityLossFraction, `${scenario.id}.thresholds.opacityLossFraction`),
		usefulLightLossFraction: thresholdLossFraction(scenario.thresholds?.usefulLightLossFraction, `${scenario.id}.thresholds.usefulLightLossFraction`),
	};
	const floors = {
		effectiveIrradiance: validateEffectiveIrradianceFloors(
			scenario.floors?.effectiveIrradiance ?? [],
			`${scenario.id}.floors.effectiveIrradiance`,
		),
	};

	if (pathParameters.startDistanceKm <= source.radiusKm) {
		throw new RangeError(`${scenario.id}.path.startDistanceKm must be greater than source.radiusKm`);
	}

	if (pathParameters.maxDistanceKm <= pathParameters.startDistanceKm) {
		throw new RangeError(`${scenario.id}.path.maxDistanceKm must be greater than path.startDistanceKm`);
	}

	return {
		id: scenario.id,
		label: scenario.label,
		description: scenario.description,
		referenceWavelengthNm,
		thresholds,
		derivedThresholds: {
			transmittanceThreshold: 1 - thresholds.opacityLossFraction,
			relativeEffectiveIrradianceThreshold: 1 - thresholds.usefulLightLossFraction,
		},
		sun,
		source,
		atmosphere,
		path: pathParameters,
		sampling,
		floors,
	};
}

function buildCoarseSamples(parameters, baselineEffectiveIrradiance) {
	const samples = [];
	const { startDistanceKm, maxDistanceKm } = parameters.path;
	const denominator = parameters.sampling.coarseSampleCount - 1;

	for (let index = 0; index < parameters.sampling.coarseSampleCount; index += 1) {
		const t = index / denominator;
		const distanceFromSunKm = startDistanceKm + (maxDistanceKm - startDistanceKm) * t;
		samples.push(evaluateAtDistance(parameters, distanceFromSunKm, baselineEffectiveIrradiance));
	}

	return samples;
}

function findCrossing(parameters, baselineEffectiveIrradiance, samples, thresholdId, remainingThreshold, crosses) {
	if (crosses(samples[0])) {
		return {
			status: 'already-crossed',
			thresholdId,
			remainingThreshold,
			lossFraction: 1 - remainingThreshold,
			...crossingLocation(samples[0]),
			evaluation: samples[0],
		};
	}

	for (let index = 1; index < samples.length; index += 1) {
		if (!crosses(samples[index])) {
			continue;
		}

		const evaluation = refineCrossing(
			parameters,
			baselineEffectiveIrradiance,
			samples[index - 1].distanceFromSunKm,
			samples[index].distanceFromSunKm,
			crosses,
		);

		return {
			status: 'crossed',
			thresholdId,
			remainingThreshold,
			lossFraction: 1 - remainingThreshold,
			...crossingLocation(evaluation),
			evaluation,
		};
	}

	return {
		status: 'not-crossed',
		thresholdId,
		remainingThreshold,
		lossFraction: 1 - remainingThreshold,
		lastEvaluation: samples[samples.length - 1],
	};
}

function refineCrossing(parameters, baselineEffectiveIrradiance, lowerDistanceKm, upperDistanceKm, crosses) {
	let lower = lowerDistanceKm;
	let upper = upperDistanceKm;
	let upperEvaluation = evaluateAtDistance(parameters, upper, baselineEffectiveIrradiance);

	for (let index = 0; index < parameters.sampling.binaryIterations; index += 1) {
		const mid = (lower + upper) / 2;
		const evaluation = evaluateAtDistance(parameters, mid, baselineEffectiveIrradiance);

		if (crosses(evaluation)) {
			upper = mid;
			upperEvaluation = evaluation;
		} else {
			lower = mid;
		}
	}

	return upperEvaluation;
}

function chooseFunctionalExtent(thresholdCrossings) {
	const candidates = Object.entries(thresholdCrossings)
		.filter(([, crossing]) => crossing.status === 'crossed' || crossing.status === 'already-crossed')
		.map(([thresholdId, crossing]) => ({
			thresholdId,
			...crossingLocation(crossing),
			status: crossing.status,
		}))
		.sort((a, b) => a.distanceFromSunKm - b.distanceFromSunKm);

	if (!candidates.length) {
		return {
			status: 'not-crossed',
			limitingThreshold: null,
			note: 'No configured light-loss threshold crossed before the maximum sampled distance.',
		};
	}

	return {
		status: 'bounded',
		limitingThreshold: candidates[0].thresholdId,
		distanceFromSunKm: candidates[0].distanceFromSunKm,
		pathDistanceKm: candidates[0].pathDistanceKm,
	};
}

function evaluateAtDistance(parameters, distanceFromSunKm, baselineEffectiveIrradiance) {
	const pathDistanceKm = distanceFromSunKm - parameters.path.startDistanceKm;
	const altitudeKm = altitudeAtPathDistance(parameters, pathDistanceKm);
	const opticalDepth = integrateOpticalDepth(parameters, distanceFromSunKm);
	const transmittance = Math.exp(-opticalDepth);
	const solidAngleSr = solarDiskSolidAngleSr(parameters.source.radiusKm, distanceFromSunKm);
	// Source map: PBRT Beer-Lambert transmittance supplies T; finite-disk geometry supplies the irradiance falloff term.
	const effectiveIrradiance = parameters.sun.directLightAvailable
		? parameters.sun.brightnessScale * solidAngleSr * transmittance
		: 0;
	const relativeEffectiveIrradiance = baselineEffectiveIrradiance === null
		? (effectiveIrradiance > 0 ? 1 : 0)
		: (baselineEffectiveIrradiance > 0 ? effectiveIrradiance / baselineEffectiveIrradiance : 0);

	return {
		distanceFromSunKm,
		pathDistanceKm,
		altitudeKm,
		opticalDepth,
		transmittance,
		transmissionLossFraction: 1 - transmittance,
		solidAngleSr,
		effectiveIrradiance,
		relativeEffectiveIrradiance,
		usefulLightLossFraction: 1 - relativeEffectiveIrradiance,
	};
}

function integrateOpticalDepth(parameters, distanceFromSunKm) {
	const lengthKm = distanceFromSunKm - parameters.path.startDistanceKm;

	if (lengthKm <= 0) {
		return 0;
	}

	const steps = Math.max(1, Math.ceil(lengthKm / parameters.sampling.integrationStepKm));
	const stepKm = lengthKm / steps;
	let opticalDepth = 0;

	// Source map: this is the midpoint-rule approximation of tau = integral sigma_t ds along the sampled source path.
	for (let index = 0; index < steps; index += 1) {
		const pathDistanceKm = (index + 0.5) * stepKm;
		const altitudeKm = altitudeAtPathDistance(parameters, pathDistanceKm);

		if (parameters.sun.elevationDeg >= 0 && altitudeKm > parameters.atmosphere.atmosphereTopKm) {
			break;
		}

		opticalDepth += extinctionAtAltitude(parameters, altitudeKm) * stepKm;
	}

	return opticalDepth;
}

function extinctionAtAltitude(parameters, altitudeKm) {
	if (altitudeKm > parameters.atmosphere.atmosphereTopKm) {
		return 0;
	}

	const clampedAltitudeKm = Math.max(0, altitudeKm);
	const densityScale = parameters.atmosphere.densityModel === 'constant'
		? 1
		: Math.exp(-clampedAltitudeKm / parameters.atmosphere.scaleHeightKm);

	return parameters.atmosphere.extinction550PerKm
		* (550 / parameters.referenceWavelengthNm) ** parameters.atmosphere.wavelengthExponent
		* densityScale;
}

function altitudeAtPathDistance(parameters, pathDistanceKm) {
	const altitudeKm = parameters.path.startAltitudeKm
		+ pathDistanceKm * Math.sin(degreesToRadians(parameters.sun.elevationDeg));

	// Local flat-profile policy: downward or below-ground paths keep sampling the densest near-surface layer.
	return Math.max(0, altitudeKm);
}

function solarDiskSolidAngleSr(radiusKm, distanceKm) {
	const ratio = radiusKm / distanceKm;
	const clampedRatio = Math.max(0, Math.min(1, ratio));
	const cosHalfAngle = Math.sqrt(1 - clampedRatio * clampedRatio);

	// Source map: finite circular-disk solid angle; for small disks this tends to pi * (radius / distance)^2.
	return 2 * Math.PI * (1 - cosHalfAngle);
}

function crossingLocation(crossingOrEvaluation) {
	const evaluation = crossingOrEvaluation.evaluation ?? crossingOrEvaluation;

	return {
		distanceFromSunKm: evaluation.distanceFromSunKm,
		pathDistanceKm: evaluation.pathDistanceKm,
	};
}

function stripDerivedParameters(parameters) {
	const { derivedThresholds, ...publicParameters } = parameters;

	return publicParameters;
}

function readScenarioSets(config) {
	if (Array.isArray(config.sets)) {
		return config.sets;
	}

	if (config.sets && typeof config.sets === 'object') {
		return Object.values(config.sets);
	}

	throw new TypeError('Light extent config requires a sets array or object');
}

function requireText(value, label) {
	if (typeof value !== 'string' || value.trim() === '') {
		throw new TypeError(`${label} must be a non-empty string`);
	}

	return value;
}

function requireDensityModel(value, label) {
	if (value === 'exponential-altitude' || value === 'constant') {
		return value;
	}

	throw new TypeError(`${label} must be "exponential-altitude" or "constant"`);
}

function thresholdLossFraction(value, label) {
	const number = finiteNumber(value, label);

	if (number < 0 || number >= 1) {
		throw new RangeError(`${label} must be in [0, 1)`);
	}

	return number;
}

function validateEffectiveIrradianceFloors(floors, label) {
	if (!Array.isArray(floors)) {
		throw new TypeError(`${label} must be an array`);
	}

	return floors.map((floor, index) => {
		const floorLabel = `${label}[${index}]`;

		if (!isPlainObject(floor)) {
			throw new TypeError(`${floorLabel} must be an object`);
		}

		return {
			id: requireText(floor.id, `${floorLabel}.id`),
			label: floor.label ? requireText(floor.label, `${floorLabel}.label`) : floor.id,
			value: nonnegativeFiniteNumber(floor.value, `${floorLabel}.value`),
			units: floor.units ? requireText(floor.units, `${floorLabel}.units`) : 'probe effective irradiance units',
			basis: floor.basis ? requireText(floor.basis, `${floorLabel}.basis`) : 'unspecified',
			description: floor.description ? requireText(floor.description, `${floorLabel}.description`) : '',
		};
	});
}

function positiveInteger(value, label, minimum = 1) {
	if (!Number.isInteger(value) || value < minimum) {
		throw new RangeError(`${label} must be an integer >= ${minimum}`);
	}

	return value;
}

function nonnegativeInteger(value, label) {
	if (!Number.isInteger(value) || value < 0) {
		throw new RangeError(`${label} must be a nonnegative integer`);
	}

	return value;
}

function positiveFiniteNumber(value, label) {
	const number = finiteNumber(value, label);

	if (number <= 0) {
		throw new RangeError(`${label} must be > 0`);
	}

	return number;
}

function nonnegativeFiniteNumber(value, label) {
	const number = finiteNumber(value, label);

	if (number < 0) {
		throw new RangeError(`${label} must be >= 0`);
	}

	return number;
}

function finiteNumber(value, label) {
	if (!Number.isFinite(value)) {
		throw new TypeError(`${label} must be a finite number`);
	}

	return value;
}

function deepMerge(base, override) {
	if (!isPlainObject(base) || !isPlainObject(override)) {
		return override === undefined ? cloneJson(base) : cloneJson(override);
	}

	const merged = {};
	const keys = new Set([...Object.keys(base), ...Object.keys(override)]);

	for (const key of keys) {
		merged[key] = deepMerge(base[key], override[key]);
	}

	return merged;
}

function cloneJson(value) {
	if (value === undefined) {
		return undefined;
	}

	if (Array.isArray(value)) {
		return value.map(cloneJson);
	}

	if (isPlainObject(value)) {
		return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, cloneJson(entry)]));
	}

	return value;
}

function isPlainObject(value) {
	return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function thresholdLine(crossing, probe, x0, y0, width, height, color) {
	if (crossing.status !== 'crossed' && crossing.status !== 'already-crossed') {
		return null;
	}

	const x = xForDistance(crossing.distanceFromSunKm, probe.samples, x0, width);

	return `<line x1="${x}" y1="${y0}" x2="${x}" y2="${y0 + height}" stroke="${color}" stroke-width="1.5" stroke-dasharray="4 4"/>`;
}

function buildLogPolyline(samples, xSelector, ySelector, x0, y0, width, height) {
	return samples.map((sample) => {
		return `${xForDistance(xSelector(sample), samples, x0, width)},${yForRemaining(ySelector(sample), y0, height)}`;
	}).join(' ');
}

function xForDistance(distanceFromSunKm, samples, x0, width) {
	const first = samples[0].distanceFromSunKm;
	const last = samples[samples.length - 1].distanceFromSunKm;
	const t = (distanceFromSunKm - first) / (last - first);

	return x0 + t * width;
}

function yForRemaining(value, y0, height) {
	const clamped = Math.max(LOG_CHART_FLOOR, Math.min(1, value));
	const logValue = Math.log10(clamped);
	const logFloor = Math.log10(LOG_CHART_FLOOR);
	const t = (logValue - logFloor) / (0 - logFloor);

	return y0 + (1 - t) * height;
}

function relativeReportPath(targetPath, reportPath) {
	if (!reportPath) {
		return normalizeOutputPath(targetPath);
	}

	const relativePath = path.relative(
		path.dirname(path.resolve(reportPath)),
		path.resolve(targetPath),
	);

	return normalizeOutputPath(relativePath || path.basename(targetPath));
}

function normalizeOutputPath(outputPath) {
	return outputPath.replaceAll('\\', '/');
}

function formatCrossing(crossing) {
	if (crossing.status === 'not-crossed') {
		return 'not crossed';
	}

	return `${formatNumber(crossing.pathDistanceKm)} km`;
}

function formatEffectiveIrradianceFloors(floorCrossings) {
	if (!floorCrossings.length) {
		return 'none';
	}

	return floorCrossings.map((crossing) => {
		return `${crossing.floor.id} \`${formatNumber(crossing.floor.value)} ${crossing.floor.units}\` -> ${formatCrossing(crossing)}`;
	}).join('; ');
}

function formatNumber(value) {
	if (value === null || value === undefined) {
		return 'n/a';
	}

	const safeValue = Math.abs(value) < EPSILON_REMAINING_FRACTION ? 0 : value;

	if (Math.abs(safeValue) >= 1000 || (Math.abs(safeValue) > 0 && Math.abs(safeValue) < 0.001)) {
		return Number(safeValue).toExponential(3);
	}

	if (Math.abs(safeValue) < 1 && Math.abs(1 - Math.abs(safeValue)) < 0.0001) {
		return Number(safeValue).toFixed(6).replace(/0+$/, '').replace(/\.$/, '');
	}

	return Number(safeValue).toFixed(4).replace(/0+$/, '').replace(/\.$/, '');
}

function degreesToRadians(degrees) {
	return degrees * Math.PI / 180;
}

function escapeXml(value) {
	return String(value)
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}
